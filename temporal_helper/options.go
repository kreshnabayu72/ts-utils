// DefaultActivityOptions returns standard activity options with 1 minute timeout and 2 retry attempts.
// Parameters:
//   - taskQueueName: optional task queue override for cross-service activities (e.g., analytics, approval services)
//
// Example:
//
//	// Local activities
//	ctx := workflow.WithActivityOptions(ctx, temporal_helper.DefaultActivityOptions())
//
//	// Cross-service activities
//	analyticsCtx := workflow.WithActivityOptions(ctx, temporal_helper.DefaultActivityOptions("analytics-reporting-service"))
func DefaultActivityOptions(taskQueue ...string) workflow.ActivityOptions {
	opts := workflow.ActivityOptions{
		StartToCloseTimeout: 1 * time.Minute,
		RetryPolicy: &temporal.RetryPolicy{
			MaximumAttempts: 2,
		},
	}

	if len(taskQueue) > 0 {
		opts.TaskQueue = taskQueue[0]
	}

	return opts
}

// DefaultChildWorkflowOptions returns standard child workflow options with 2 retry attempts.
// Uses default ParentClosePolicy (TERMINATE - child dies with parent).
//
// Use this for blocking child workflows where parent waits for completion.
//
// Example:
//
//	childCtx := workflow.WithChildOptions(ctx, temporal_helper.DefaultChildWorkflowOptions())
//	err := workflow.ExecuteChildWorkflow(childCtx, "ConfirmPasswordWorkflow", param).Get(ctx, nil)
func DefaultChildWorkflowOptions(taskQueue ...string) workflow.ChildWorkflowOptions {
	// Use default ParentClosePolicy (TERMINATE - child dies with parent).
	// Use default WorkflowExecutionTimeout (let it fail via activity timeout).
	opts := workflow.ChildWorkflowOptions{
		RetryPolicy: &temporal.RetryPolicy{
			MaximumAttempts: 2,
		},
	}

	if len(taskQueue) > 0 {
		opts.TaskQueue = taskQueue[0]
	}

	return opts
}

// FireAndForgetChildWorkflowOptions returns child workflow options for async/background operations.
// Uses ABANDON policy so child continues running even if parent fails or completes.
//
// Parameters:
//   - ctx: workflow context (for deterministic workflow ID generation)
//   - workflowID: (Optional) base ID for the child workflow (will be made unique with timestamp), if you leave it empty, auto generated by default
//   - taskQueue: (Optional) optional task queue override
//
// Example:
//
//	opts := temporal_helper.FireAndForgetChildWorkflowOptions(
//	    ctx,
//	    fmt.Sprintf("send-email-verification-%d", userID),
//	)
//	childCtx := workflow.WithChildOptions(ctx, opts)
//	future := workflow.ExecuteChildWorkflow(childCtx, "SendEmailWorkflow", param)
//	// Wait only for spawn, not completion
//	var childWE workflow.Execution
//	future.GetChildWorkflowExecution().Get(ctx, &childWE)
func FireAndForgetChildWorkflowOptions(
	ctx workflow.Context,
	// If you leave it empty, auto generated by default
	workflowID string,
	// If you leave it empty, use parent's task queue
	taskQueue ...string,
) workflow.ChildWorkflowOptions {
	// Use PARENT_CLOSE_POLICY_ABANDON (ABANDON - child continues running even if parent fails or completes).
	// Use default WorkflowExecutionTimeout (let it fail via activity timeout).
	opts := workflow.ChildWorkflowOptions{
		ParentClosePolicy: enums.PARENT_CLOSE_POLICY_ABANDON,
		RetryPolicy: &temporal.RetryPolicy{
			MaximumAttempts: 2,
		},
	}

	if workflowID != "" {
		// Generate deterministic unique ID
		opts.WorkflowID = fmt.Sprintf("%s-%d", workflowID, workflow.Now(ctx).Unix())
	}

	if len(taskQueue) > 0 {
		opts.TaskQueue = taskQueue[0]
	} else {
		// Use parent's task queue if not specified
		opts.TaskQueue = workflow.GetInfo(ctx).TaskQueueName
	}

	return opts
}
